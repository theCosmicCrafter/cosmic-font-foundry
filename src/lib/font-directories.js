/**
 * Builds an HTTPS destination URL for an external font directory, injecting an encoded
 * search query when supported and provided.
 */
export function buildDirectoryUrl(dir, rawQuery = "") {
  const q = String(rawQuery || "").trim();
  if (q && dir?.searchUrlTemplate) {
    return dir.searchUrlTemplate.replace("{q}", encodeURIComponent(q));
  }
  return dir?.url || "https://www.google.com/fonts";
}
